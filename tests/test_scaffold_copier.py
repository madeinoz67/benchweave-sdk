"""R-2 port parity: the copier render equals the committed fixture, byte for byte.

The fixture under ``tests/fixtures/scaffold_expected/`` was generated by the
pre-copier ``create_project``/``create_ui_resources`` (string-constant
implementation) and proven byte-equal to the last pre-copier release output
(v0.4.1 tag) at the cutover — that one-time back-check is what makes later
``adopt``-style claims about template@vN renders honest. Every generated file
is asserted byte-exactly (exhaustive, not a sample); the only permitted
addition over the pre-copier tree is ``.copier-answers.yml``.

Regenerating the fixture (after a deliberate template change, an SDK version
bump, or a vendored OTDP version move — the answers/descriptor/pyproject pins
carry those versions by design) is what `make release-cut VERSION=x.y.z`
performs mechanically (occurrence-validated; issue #408). The manual
procedure, for out-of-band repairs only:

    tmp=$(mktemp -d)
    uv run python -c "from pathlib import Path; \
from benchweave_sdk.scaffold import create_project; \
from benchweave_sdk.presentation import create_ui_resources; \
create_project(Path('$tmp/base'), 'example_plugin'); \
create_project(Path('$tmp/ui'), 'example_plugin', with_ui=True); \
create_ui_resources(Path('$tmp/ui'), 'example_plugin')"
    # then copy each tree over tests/fixtures/scaffold_expected/<arm>/ and
    # rewrite the answers file's _src_path/_commit to the canonical pin
    # (see ``_expected_answers`` below for the exact bytes).

A green run here means the template, the render path and the fixture agree;
any of the three drifting reddens exactly the arm that drifted.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from benchweave_sdk import __version__
from benchweave_sdk.presentation import create_ui_resources
from benchweave_sdk.scaffold import create_project

FIXTURES = Path(__file__).parent / "fixtures" / "scaffold_expected"
REPO_ROOT = Path(__file__).resolve().parents[1]
CANONICAL_TEMPLATE_URL = "https://github.com/madeinoz67/benchweave-sdk"


def test_line_endings_are_pinned_lf_for_the_scaffold_surfaces() -> None:
    """PR #93's Windows lane: the byte-parity surfaces must check out and
    render LF on every OS. The template and the fixtures carry explicit
    eol=lf rows so a future relaxation of the repository's global rule
    reddens HERE, not on a Windows CI lane."""
    attributes = (REPO_ROOT / ".gitattributes").read_text(encoding="utf-8")
    rows = {
        line.split()[0]: line
        for line in attributes.splitlines()
        if line and not line.startswith("#") and line.split()
    }
    for pinned in ("template/**", "tests/fixtures/scaffold_expected/**"):
        assert pinned in rows, f"{pinned} must carry its own .gitattributes row"
        assert "eol=lf" in rows[pinned], f"{pinned} must pin eol=lf"


def test_line_endings_are_pinned_lf_for_the_phase2_patched_surfaces() -> None:
    """Wave 4: the phase-2 patch's two surfaces must check out LF on every
    OS. The phase-2 patch is generated from the CHECKED-OUT bytes and must
    apply to the checked-out bytes; a CRLF checkout (the Windows runner's
    global autocrlf) makes the context mismatch and git apply --check dies
    ('patch does not apply', the sdk(windows-latest) lane's RED). Same
    doctrine as the scaffold rows above (PR #93): the explicit rows pin
    the surfaces so a future relaxation of the global line reddens HERE.
    website/ is pinned as a whole directory, not just index.html: the dir
    ships to the public site verbatim, so byte-consistency is the posture
    for all of it."""
    attributes = (REPO_ROOT / ".gitattributes").read_text(encoding="utf-8")
    rows = {
        line.split()[0]: line
        for line in attributes.splitlines()
        if line and not line.startswith("#") and line.split()
    }
    for pinned in ("great-docs.yml", "website/**"):
        assert pinned in rows, f"{pinned} must carry its own .gitattributes row"
        assert "eol=lf" in rows[pinned], f"{pinned} must pin eol=lf"


def test_rendered_answers_carry_no_carriage_returns(tmp_path: Path) -> None:
    """The answers pin writes BYTES: Path.write_text opens text mode, and
    text mode translates newlines to os.linesep — CRLF on Windows, which
    broke the fixture comparison on that lane (PR #93). Byte writes cannot
    translate, on any platform."""
    destination = tmp_path / "example_plugin"
    create_project(destination, "example_plugin")
    raw = (destination / ".copier-answers.yml").read_bytes()
    assert b"\r" not in raw
    assert raw == (FIXTURES / "base" / ".copier-answers.yml").read_bytes()


def test_rendered_tree_carries_no_carriage_returns(tmp_path: Path) -> None:
    """The WHOLE render is LF on every platform (PR #93's Windows lane):
    rendered members arrived CRLF there even though the template checkout
    is LF, so create_project normalizes the rendered tree after copier
    runs. Byte-compare every member against the fixture — the same R-2
    arm, stated as a line-ending contract."""
    destination = tmp_path / "example_plugin"
    create_project(destination, "example_plugin")
    rendered = _tree(destination)
    for relative, content in rendered.items():
        assert b"\r" not in content, relative
    assert rendered == _tree(FIXTURES / "base")


def test_enforce_lf_rewrites_crlf_and_never_touches_git(tmp_path: Path) -> None:
    """The normalization helper's contract, unit-pinned: CRLF becomes LF
    in every rendered text file (nested included), and .git is never
    touched — upgrade runs it inside a live project repository."""
    from benchweave_sdk.scaffold import _enforce_lf

    planted = tmp_path / "planted"
    (planted / "src" / "pkg").mkdir(parents=True)
    (planted / "src" / "pkg" / "adapter.py").write_bytes(b"def go():\r\n    pass\r\n")
    (planted / "AI-GUIDE.md").write_bytes(b"# Guide\r\n\r\nbody\r\n")
    (planted / "already.md").write_bytes(b"# fine\n")
    git_dir = planted / ".git"
    git_dir.mkdir()
    (git_dir / "index").write_bytes(b"BIN\r\nARY\r\n")
    _enforce_lf(planted)
    assert (planted / "src" / "pkg" / "adapter.py").read_bytes() == b"def go():\n    pass\n"
    assert (planted / "AI-GUIDE.md").read_bytes() == b"# Guide\n\nbody\n"
    assert (planted / "already.md").read_bytes() == b"# fine\n"
    assert (git_dir / "index").read_bytes() == b"BIN\r\nARY\r\n", ".git must stay untouched"


def _tree(root: Path) -> dict[str, bytes]:
    return {
        entry.relative_to(root).as_posix(): entry.read_bytes().replace(b"\r\n", b"\n")
        for entry in sorted(root.rglob("*"))
        if entry.is_file()
    }


def _assert_tree_equal(rendered: Path, fixture: Path) -> None:
    actual, expected = _tree(rendered), _tree(fixture)
    assert sorted(actual) == sorted(expected), (
        f"file sets differ; missing from render: {sorted(set(expected) - set(actual))}, "
        f"unexpected in render: {sorted(set(actual) - set(expected))}"
    )
    for relative in sorted(expected):
        assert actual[relative] == expected[relative], f"bytes differ: {relative}"


def test_new_project_tree_matches_fixture_base(tmp_path: Path) -> None:
    destination = tmp_path / "example_plugin"
    create_project(destination, "example_plugin")
    _assert_tree_equal(destination, FIXTURES / "base")


def test_new_project_tree_matches_fixture_with_ui(tmp_path: Path) -> None:
    destination = tmp_path / "example_plugin"
    create_project(destination, "example_plugin", with_ui=True)
    create_ui_resources(destination, "example_plugin")
    _assert_tree_equal(destination, FIXTURES / "ui")


def _answers_of(project: Path) -> dict[str, str]:
    lines = (project / ".copier-answers.yml").read_text(encoding="utf-8").splitlines()
    return {
        line.split(":", 1)[0].strip(): line.split(":", 1)[1].strip() for line in lines[1:]
    }


def test_answers_pin_records_canonical_provenance(tmp_path: Path) -> None:
    """``new`` pins the answers to the tagged canonical repo, never the render source.

    The render happens from a materialized copy of the packaged template (a
    temp directory); without the pin, ``_src_path`` would name that ephemeral
    path and ``_commit`` would be absent (non-git template), leaving the
    project un-updatable. The pin is what makes the answers durable.
    """
    destination = tmp_path / "example_plugin"
    create_project(destination, "example_plugin")
    answers = _answers_of(destination)
    assert answers["_src_path"] == CANONICAL_TEMPLATE_URL
    assert answers["_commit"] == f"v{__version__}"
    assert answers["package_name"] == "example_plugin"
    assert answers["with_ui"] == "false"


def test_answers_pin_records_with_ui_arm(tmp_path: Path) -> None:
    destination = tmp_path / "example_plugin"
    create_project(destination, "example_plugin", with_ui=True)
    assert _answers_of(destination)["with_ui"] == "true"


def test_scaffold_extra_absent_refusal_names_install_command(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """The [scaffold] extra is optional; its absence refuses loudly, not with a traceback."""
    import sys

    # Suppress the module itself so the real _load_copier translation runs —
    # patching the seam would bypass the very refusal under test.
    monkeypatch.setitem(sys.modules, "copier", None)
    with pytest.raises(ValueError, match=r"^scaffold_extra_absent: ") as excinfo:
        create_project(tmp_path / "demo", "demo_plugin")
    assert "benchweave-sdk[scaffold]" in str(excinfo.value)
    assert not (tmp_path / "demo").exists()
    assert not (tmp_path / "demo.partial").exists()
