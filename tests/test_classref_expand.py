"""Class-reference expander acceptance tests (gateway #463 L2, A1/A2/A3/A7).

Fixtures: tests/fixtures/classref/ (generated by scripts/gen_classref_fixtures.py;
all names invented, Veridian family). RED-first: committed before the expander.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from benchweave_sdk.classref import (
    LAYOUT_EXTENSION_KEY,
    derive_ui,
    find_reference,
)
from benchweave_sdk.presentation import validate_presentation
from benchweave_sdk.served import active_version

FIXTURES = Path(__file__).parent / "fixtures" / "classref"
REFERENCE = find_reference("otdp.logic_analyser/1.0.0")


def _load(name: str) -> dict:
    return json.loads((FIXTURES / name).read_bytes())


def _derive(name: str):
    return derive_ui((FIXTURES / name).read_bytes(), REFERENCE, descriptor_path=FIXTURES / name)


def _raw(doc: dict) -> bytes:
    return (json.dumps(doc, indent=2) + "\n").encode()


def _validated(derived, descriptor_name: str):
    resources = {"manifest.json": _raw(derived.manifest)}
    for slug, scaffold in derived.preset_scaffolds.items():
        resources[f"presets/{slug}.json"] = _raw(scaffold)
    resources["settings/configure.schema.json"] = _raw(derived.settings_schema)
    return validate_presentation(
        _raw(derived.envelope),
        descriptor_raw=(FIXTURES / descriptor_name).read_bytes(),
        resources=resources,
        binding_catalogue=derived.catalogue,
    )


def test_reference_resolves_from_vendored_tree() -> None:
    assert REFERENCE is not None
    assert REFERENCE["profile_id"] == "otdp.logic_analyser/1.0.0"
    assert REFERENCE["targets"]["plugin_ui"] == ">=0.3.1"


def test_f1_expands_and_validates_a1() -> None:
    derived = _derive("descriptor-f1.json")
    report = _validated(derived, "descriptor-f1.json")
    assert report.valid, [(f.code, f.path, f.message) for f in report.findings]
    plot = derived.manifest["pages"][0]["plots"][0]
    assert plot["kind"] == "digital_lanes"
    assert len(plot["y"]) == 2
    groups = plot["lane_groups"]
    assert len(groups) == 1
    assert groups[0]["id"] == "lanes-1"
    assert groups[0]["label"] == "D1-D2"
    assert groups[0]["member_ids"] == ["d0", "d1"]
    assert groups[0]["radix"] == "hex"
    assert plot["decoder_lanes"] == []
    version = active_version("plugin-ui")
    assert derived.manifest["contract_version"] == version
    assert derived.envelope["contract_version"] == version
    assert derived.catalogue["contract_version"] == version
    block = derived.manifest["extensions"][LAYOUT_EXTENSION_KEY]
    assert block["contract_version"] == active_version(
        "plugin-ui-class-reference"
    )
    assert block["pages"][0]["page_id"] == "capture"
    run = block["pages"][0]["sections"][1]
    kinds = [
        (node.get("binding_id"), node["kind"], node.get("field"))
        for node in run["children"]
    ]
    assert kinds == [
        ("arm", "numeric", "max_duration_ms"),
        ("arm", "button", None),
        ("abort", "button", None),
    ]


def test_f2_d_series_a2() -> None:
    derived = _derive("descriptor-f2.json")
    report = _validated(derived, "descriptor-f2.json")
    assert report.valid, [(f.code, f.path, f.message) for f in report.findings]
    plot = derived.manifest["pages"][0]["plots"][0]
    assert len(plot["y"]) == 32
    groups = plot["lane_groups"]
    assert [g["label"] for g in groups] == ["D1-D8", "D9-D16", "D17-D24", "D25-D32"]
    assert groups[0]["member_ids"] == [f"d{i}" for i in range(8)]
    assert plot["decoder_lanes"] == []
    # D2 data trace: the y variable ids are descriptor channel ids verbatim.
    assert set(plot["y"]) == {f"d{i}" for i in range(32)}


def test_refusals_red_a3() -> None:
    # 0 digital_input channels.
    with pytest.raises(ValueError, match="^classref_no_lanes:"):
        derive_ui((FIXTURES / "refusal-no-lanes.json").read_bytes(), REFERENCE)
    # >64 digital_input channels.
    with pytest.raises(ValueError, match="^classref_lane_ceiling:"):
        derive_ui((FIXTURES / "refusal-lane-ceiling.json").read_bytes(), REFERENCE)
    # A required-class action absent from the descriptor.
    with pytest.raises(ValueError, match="^classref_required_action_absent:"):
        derive_ui((FIXTURES / "refusal-action-absent.json").read_bytes(), REFERENCE)
    # The reference names an action URN absent from the served OTDP catalog.
    with pytest.raises(ValueError, match="^classref_unknown_action:"):
        derive_ui(
            (FIXTURES / "descriptor-f1.json").read_bytes(),
            {**REFERENCE, "slots": {**REFERENCE["slots"],
             "ghost": {"kind": "procedure", "action": "otdp.logic_analyser.poltergeist/1.0.0"}}},
        )


def test_expectation_document_resolves_expressions() -> None:
    derived = _derive("descriptor-f1.json")
    expect = derived.expectation
    inventory = expect["inventory"]
    assert inventory["n_lanes"] == 2
    assert inventory["n_groups"] == 1
    assert inventory["n_decoders"] == 0
    assert inventory["n_run_actions"] == 2
    assert inventory["n_pages"] == 3
    assert inventory["n_configure_fields"] >= 1
    components = expect["components"]
    assert components["digital-lanes"] == {
        "count": 1, "per_page": "capture",
        "attribute": {"data-bw-lane-kind=channel": 2,
                      "data-bw-lane-kind=group": 1,
                      "data-bw-lane-kind=decoder": 0},
    }
    assert components["button"] == {"count": 2, "per_page": "capture"}
    assert components["mode-banner"] == {"count": 1, "per_page": "*"}


